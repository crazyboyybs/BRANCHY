using Branchy.Services;
using Microsoft.Windows.AppLifecycle;
using Microsoft.UI.Xaml;
using Microsoft.UI.Xaml.Controls;
using Microsoft.UI.Composition.SystemBackdrops;
using ILaunchActivatedEventArgs = Windows.ApplicationModel.Activation.ILaunchActivatedEventArgs;

namespace Branchy;

/// <summary>Provides the application lifetime and active window.</summary>
public partial class App : Application
{
    private const string RepositoryArgumentPrefix = "--repository=";

    /// <summary>Gets the active application window.</summary>
    public Window? MainWindow { get; private set; }

    /// <summary>Gets the user preference store shared by all application surfaces.</summary>
    public IAppSettingsService Settings { get; } = new AppSettingsService();

    /// <summary>Gets the repository path supplied by shell activation.</summary>
    public string InitialRepositoryPath { get; private set; } = Environment.CurrentDirectory;

    /// <summary>Gets whether File Explorer explicitly supplied the initial folder.</summary>
    public bool HasInitialRepositoryRequest { get; private set; }

    /// <summary>Initializes the application resources.</summary>
    public App()
    {
        Settings.ApplyLanguageOverride();
        InitializeComponent();
    }

    /// <inheritdoc />
    protected override void OnLaunched(LaunchActivatedEventArgs args)
    {
        if (DesktopAcrylicController.IsSupported())
        {
            // Application.Resources is unavailable until application construction completes.
            // Also covers tooltips generated by ToolTipService and native controls.
            Resources[typeof(ToolTip)] = (Style)Resources["DesktopAcrylicToolTipStyle"];
        }

        string arguments = GetLaunchArguments(args.Arguments);
        if (arguments.StartsWith(RepositoryArgumentPrefix, StringComparison.Ordinal))
        {
            string requestedPath = arguments[RepositoryArgumentPrefix.Length..].Trim().Trim('"');
            if (Directory.Exists(requestedPath))
            {
                InitialRepositoryPath = requestedPath;
                HasInitialRepositoryRequest = true;
            }
        }

        var mainWindow = new MainWindow();
        MainWindow = mainWindow;
        mainWindow.Activate();
        mainWindow.BringToForeground();
        mainWindow.DispatcherQueue.TryEnqueue(mainWindow.BringToForeground);
    }

    private static string GetLaunchArguments(string fallbackArguments)
    {
        AppActivationArguments activation = AppInstance.GetCurrent().GetActivatedEventArgs();
        if (activation.Kind == ExtendedActivationKind.Launch &&
            activation.Data is ILaunchActivatedEventArgs launchArguments &&
            !string.IsNullOrWhiteSpace(launchArguments.Arguments))
        {
            return launchArguments.Arguments;
        }

        if (!string.IsNullOrWhiteSpace(fallbackArguments))
        {
            return fallbackArguments;
        }

        return Environment.GetCommandLineArgs()
            .Skip(1)
            .FirstOrDefault(argument =>
                argument.StartsWith(RepositoryArgumentPrefix, StringComparison.Ordinal))
            ?? string.Empty;
    }
}
